/** Dados completos de uma habilidade a partir do código. */
export function bnccInfo(code) {
  const entry = BNCC[code]
  if (!entry) return { code, grade: null, subject: null, unit: '—', text: 'Habilidade não catalogada.' }
  return {
    code,
    grade: Number(code.slice(2, 4)),
    subject: SUBJECT_OF_PREFIX[code.slice(4, 6)] ?? null,
    unit: entry.u,
    text: entry.t,
  }
}

/** Todas as habilidades de uma matéria/série (usado no painel de progresso). */
export function bnccFor(subject, grade) {
  const gradeTag = String(grade).padStart(2, '0')
  return Object.keys(BNCC)
    .filter((code) => code.slice(2, 4) === gradeTag && SUBJECT_OF_PREFIX[code.slice(4, 6)] === subject)
    .map(bnccInfo)
}
